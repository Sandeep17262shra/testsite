export function resolveJewelryString(translations, key) {
  const value = translations?.strings?.[key];
  if (typeof value === "string" && value.trim()) return value;
  return JEWELRY_UI_STRINGS[key] ?? "";
}

/** Keep a store catalog name when it is not the built-in English label. */
export function catalogOrUi(catalogLabel, english, translated) {
  const catalog = String(catalogLabel || "").trim();
  if (!catalog || catalog === english) return translated || english;
  return catalog;
}

export function formatCountedLabel(template, count) {
  return String(template || "").replaceAll("{count}", String(count));
}
